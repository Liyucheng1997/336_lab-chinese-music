// ── 编配工具 ──────────────────────────────────────────
function shiftNote(t, n) {
  const m = /^([#b]?)([0-7])([',]*)(.*)$/.exec(t);
  if (!m || m[2] === '0') return t;
  const oct = [...m[3]].reduce((a, c) => a + (c === "'" ? 1 : -1), 0) + n;
  return m[1] + m[2] + (oct > 0 ? "'".repeat(oct) : ','.repeat(-oct)) + m[4];
}

// 整段移高 / 移低 n 个八度
function shift(str, n) {
  return str
    .split(/(\s+)/)
    .map((tok) => {
      if (!tok.trim()) return tok;
      let pre = '';
      if (tok[0] === '~' || tok[0] === '^') {
        pre = tok[0];
        tok = tok.slice(1);
      }
      return pre + tok.split('+').map((p) => shiftNote(p, n)).join('+');
    })
    .join('');
}

// 八度叠奏：每个单音加上高八度
function octaves(str) {
  return str
    .split(/(\s+)/)
    .map((tok) => (/^[#b]?[1-7][',]*[_=.]*!?$/.test(tok) ? `${tok}+${shiftNote(tok, 1)}` : tok))
    .join('');
}

